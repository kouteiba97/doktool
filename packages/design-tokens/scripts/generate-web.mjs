// Writes the Admin Web token outputs of this package from design/tokens/:
//   web/tailwind-preset.mjs — the Tailwind preset as an ES module (the handoff file is CommonJS);
//   web/tokens.css          — the token stylesheet, with its font URLs pointing at design/system/fonts.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTailwindPreset } from './drift.mjs';

const repoRoot = fileURLToPath(new URL('../../../', import.meta.url));
const outputsDir = path.join(repoRoot, 'design', 'tokens');
export const WEB_DIR = fileURLToPath(new URL('../web/', import.meta.url));
export const WEB_PRESET = path.join(WEB_DIR, 'tailwind-preset.mjs');
export const WEB_CSS = path.join(WEB_DIR, 'tokens.css');

/** From packages/design-tokens/web/ to design/system/fonts/. */
const FONT_PREFIX = '../../../design/system/fonts/';

export async function renderWeb() {
  const [presetCode, css] = await Promise.all([
    readFile(path.join(outputsDir, 'tailwind.preset.js'), 'utf8'),
    readFile(path.join(outputsDir, 'tokens.css'), 'utf8'),
  ]);
  const preset = loadTailwindPreset(presetCode);
  const presetModule =
    '// Generated by `npm run generate:web -w @doktool/design-tokens` from design/tokens/tailwind.preset.js. Do not edit.\n' +
    `export default ${JSON.stringify(preset, null, 2)};\n`;
  const webCss =
    '/* Generated by `npm run generate:web -w @doktool/design-tokens` from design/tokens/tokens.css. Do not edit. */\n' +
    css.replace(/\r\n/g, '\n').replaceAll('url("../system/fonts/', `url("${FONT_PREFIX}`);
  return { presetModule, webCss };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { presetModule, webCss } = await renderWeb();
  await mkdir(WEB_DIR, { recursive: true });
  await writeFile(WEB_PRESET, presetModule, 'utf8');
  await writeFile(WEB_CSS, webCss, 'utf8');
  console.log('Wrote packages/design-tokens/web/{tailwind-preset.mjs,tokens.css}');
}
