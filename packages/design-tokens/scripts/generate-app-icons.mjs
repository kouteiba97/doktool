// Generates the Flutter app's launcher icons from the design system's app icon
// (design/system/assets/Logos/doktool-app-icon.svg). Run after the icon changes:
//   npm run generate:app-icons -w @doktool/design-tokens
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const repoRoot = fileURLToPath(new URL('../../../', import.meta.url));
const source = path.join(repoRoot, 'design/system/assets/Logos/doktool-app-icon.svg');
const androidRes = path.join(repoRoot, 'apps/mobile/android/app/src/main/res');
const iosIcons = path.join(repoRoot, 'apps/mobile/ios/Runner/Assets.xcassets/AppIcon.appiconset');

const svg = await readFile(source, 'utf8');
const tile = /<rect width="1024" height="1024" rx="(\d+)" fill="(#[0-9a-fA-F]{6})"\/>/.exec(svg);
if (!tile) throw new Error(`${source}: the background tile was not found`);
const [tileElement, , background] = tile;
/** The glyph alone, on transparency (Android adaptive foreground). */
const glyph = svg.replace(tileElement, '');
/** Full bleed, no rounded corners: iOS masks the icon itself and refuses transparency. */
const square = svg.replace(tileElement, `<rect width="1024" height="1024" fill="${background}"/>`);

const render = (markup, size) =>
  sharp(Buffer.from(markup), { density: Math.max(72, (72 * size) / 1024) * 4 })
    .resize(size, size)
    .png();

// Android launcher densities (dp × density factor).
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
/** Adaptive icons are 108 dp with a 72 dp safe circle; at 82 % of the tile, the glyph (54 × 62 % of the tile, rounded corners) stays inside it. */
const ADAPTIVE_DP = 108;
const TILE_SCALE = 0.82;

for (const [name, factor] of Object.entries(DENSITIES)) {
  const folder = path.join(androidRes, `mipmap-${name}`);
  await mkdir(folder, { recursive: true });
  await render(svg, Math.round(48 * factor)).toFile(path.join(folder, 'ic_launcher.png'));
  const size = Math.round(ADAPTIVE_DP * factor);
  const inner = Math.round(size * TILE_SCALE);
  const offset = Math.round((size - inner) / 2);
  await sharp({
    create: { width: size, height: size, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
  })
    .composite([{ input: await render(glyph, inner).toBuffer(), left: offset, top: offset }])
    .png()
    .toFile(path.join(folder, 'ic_launcher_foreground.png'));
}

await mkdir(path.join(androidRes, 'mipmap-anydpi-v26'), { recursive: true });
await writeFile(
  path.join(androidRes, 'mipmap-anydpi-v26/ic_launcher.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packages/design-tokens/scripts/generate-app-icons.mjs from the design system icon. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
`,
);
await writeFile(
  path.join(androidRes, 'values/ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packages/design-tokens/scripts/generate-app-icons.mjs: the app icon's tile colour. -->
<resources>
    <color name="ic_launcher_background">${background.toUpperCase()}</color>
</resources>
`,
);

const contents = JSON.parse(await readFile(path.join(iosIcons, 'Contents.json'), 'utf8'));
for (const image of contents.images) {
  const points = Number.parseFloat(image.size.split('x')[0]);
  const scale = Number.parseInt(image.scale, 10);
  await render(square, Math.round(points * scale))
    .flatten({ background })
    .toFile(path.join(iosIcons, image.filename));
}

console.log(
  `App icons written: Android (legacy + adaptive, 5 densities), iOS (${contents.images.length} sizes).`,
);
