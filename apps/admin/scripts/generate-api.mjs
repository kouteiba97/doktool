// Generates src/api/schema.d.ts (typed paths for openapi-fetch) from packages/api-contract.
// `--check` fails when the committed file is stale (CI).
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const contract = new URL('../../../packages/api-contract/openapi.json', import.meta.url);
const output = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));

const document = JSON.parse(await readFile(contract, 'utf8'));
const ast = await openapiTS(document, { alphabetize: true, exportType: true });
const rendered =
  '// Generated by `npm run generate:api -w @doktool/admin` from packages/api-contract/openapi.json. Do not edit.\n' +
  astToString(ast);

if (process.argv.includes('--check')) {
  const committed = await readFile(output, 'utf8').catch(() => '');
  if (committed.replace(/\r\n/g, '\n') !== rendered) {
    console.error(
      'apps/admin/src/api/schema.d.ts is stale: run `npm run generate:api -w @doktool/admin`',
    );
    process.exit(1);
  }
  console.log('Admin API types match the OpenAPI contract.');
} else {
  await writeFile(output, rendered, 'utf8');
  console.log('Wrote apps/admin/src/api/schema.d.ts');
}
