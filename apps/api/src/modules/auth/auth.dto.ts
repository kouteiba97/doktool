import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  Equals,
  IsEnum,
  IsInt,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { DevicePlatform, Language } from '../../generated/prisma/enums.js';
import { OTP_DIGITS, PASSWORD_MAX_LENGTH, PASSWORD_MIN_LENGTH } from './auth.policy.js';
import type { OtpChallengeView } from './otp.service.js';
import type { AuthTokens, SessionView } from './sessions.service.js';

const OTP_CODE = new RegExp(`^\\d{${OTP_DIGITS}}$`);

export class DeviceDto {
  @ApiProperty({ description: 'Installation id generated by the app and kept in secure storage.' })
  @IsString()
  @MinLength(8)
  @MaxLength(128)
  id!: string;

  @ApiPropertyOptional({ example: 'Pixel 8' })
  @IsOptional()
  @IsString()
  @MaxLength(120)
  name?: string;

  @ApiProperty({ enum: DevicePlatform, enumName: 'DevicePlatform' })
  @IsEnum(DevicePlatform)
  platform!: DevicePlatform;
}

class LanguageField {
  @ApiPropertyOptional({ enum: Language, enumName: 'Language', default: 'FR' })
  @IsOptional()
  @IsEnum(Language)
  language?: Language;
}

export class SignUpDto extends LanguageField {
  @ApiProperty({ description: 'E-mail address or mobile number.', example: 'amina@example.dz' })
  @IsString()
  @MaxLength(254)
  identifier!: string;

  @ApiProperty({ minLength: PASSWORD_MIN_LENGTH, maxLength: PASSWORD_MAX_LENGTH })
  @IsString()
  @MinLength(PASSWORD_MIN_LENGTH)
  @MaxLength(PASSWORD_MAX_LENGTH)
  password!: string;

  @ApiProperty({ maxLength: 80 })
  @IsString()
  @Matches(/\S/)
  @MaxLength(80)
  firstName!: string;

  @ApiProperty({ maxLength: 80 })
  @IsString()
  @Matches(/\S/)
  @MaxLength(80)
  lastName!: string;

  @ApiProperty({ example: 16 })
  @IsInt()
  @Min(1)
  @Max(999)
  wilayaCode!: number;

  @ApiProperty({ description: 'Must be true: the person accepted the terms shown.' })
  @Equals(true)
  acceptTerms!: boolean;

  @ApiProperty({ description: 'Version of the terms the app displayed.' })
  @IsString()
  @MaxLength(40)
  termsVersion!: string;
}

export class ConfirmSignUpDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  challengeId!: string;

  @ApiProperty({ example: '123456' })
  @Matches(OTP_CODE)
  code!: string;

  @ApiProperty({ type: DeviceDto })
  @ValidateNested()
  @Type(() => DeviceDto)
  device!: DeviceDto;
}

export class ResendCodeDto extends LanguageField {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  challengeId!: string;
}

export class SignInDto {
  @ApiProperty({ description: 'E-mail address or mobile number.' })
  @IsString()
  @MaxLength(254)
  identifier!: string;

  @ApiProperty()
  @IsString()
  @MinLength(1)
  @MaxLength(PASSWORD_MAX_LENGTH)
  password!: string;

  @ApiProperty({ type: DeviceDto })
  @ValidateNested()
  @Type(() => DeviceDto)
  device!: DeviceDto;
}

export class RefreshDto {
  @ApiProperty()
  @IsString()
  @MinLength(20)
  @MaxLength(200)
  refreshToken!: string;

  @ApiProperty()
  @IsString()
  @MinLength(8)
  @MaxLength(128)
  deviceId!: string;
}

export class PasswordResetRequestDto extends LanguageField {
  @ApiProperty({ description: 'E-mail address or mobile number.' })
  @IsString()
  @MaxLength(254)
  identifier!: string;
}

export class PasswordResetConfirmDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  challengeId!: string;

  @ApiProperty({ example: '123456' })
  @Matches(OTP_CODE)
  code!: string;

  @ApiProperty({ minLength: PASSWORD_MIN_LENGTH, maxLength: PASSWORD_MAX_LENGTH })
  @IsString()
  @MinLength(PASSWORD_MIN_LENGTH)
  @MaxLength(PASSWORD_MAX_LENGTH)
  newPassword!: string;
}

export class OtpChallengeDto {
  @ApiProperty({ format: 'uuid' })
  challengeId!: string;

  @ApiProperty({ enum: ['EMAIL', 'SMS'] })
  channel!: 'EMAIL' | 'SMS';

  @ApiProperty({ example: 'a•••@example.dz' })
  destinationHint!: string;

  @ApiProperty({ format: 'date-time' })
  expiresAt!: string;

  @ApiProperty({ format: 'date-time' })
  resendAvailableAt!: string;

  static from(view: OtpChallengeView): OtpChallengeDto {
    return {
      challengeId: view.challengeId,
      channel: view.channel,
      destinationHint: view.destinationHint,
      expiresAt: view.expiresAt.toISOString(),
      resendAvailableAt: view.resendAvailableAt.toISOString(),
    };
  }
}

export class AuthTokensDto {
  @ApiProperty({ format: 'uuid' })
  sessionId!: string;

  @ApiProperty()
  accessToken!: string;

  @ApiProperty({ format: 'date-time' })
  accessTokenExpiresAt!: string;

  @ApiProperty({ description: 'Store in secure storage; single use (rotated on refresh).' })
  refreshToken!: string;

  @ApiProperty({ format: 'date-time' })
  refreshTokenExpiresAt!: string;

  static from(tokens: AuthTokens): AuthTokensDto {
    return {
      sessionId: tokens.sessionId,
      accessToken: tokens.accessToken,
      accessTokenExpiresAt: tokens.accessTokenExpiresAt.toISOString(),
      refreshToken: tokens.refreshToken,
      refreshTokenExpiresAt: tokens.refreshTokenExpiresAt.toISOString(),
    };
  }
}

export class SessionDto {
  @ApiProperty({ format: 'uuid' })
  id!: string;

  @ApiProperty({ type: String, nullable: true })
  deviceName!: string | null;

  @ApiProperty({ enum: DevicePlatform, enumName: 'DevicePlatform' })
  platform!: DevicePlatform;

  @ApiProperty({ format: 'date-time' })
  createdAt!: string;

  @ApiProperty({ format: 'date-time' })
  lastUsedAt!: string;

  @ApiProperty({ description: 'True for the session making this request.' })
  current!: boolean;

  static from(view: SessionView, currentSessionId: string): SessionDto {
    return {
      id: view.id,
      deviceName: view.deviceName,
      platform: view.platform,
      createdAt: view.createdAt.toISOString(),
      lastUsedAt: view.lastUsedAt.toISOString(),
      current: view.id === currentSessionId,
    };
  }
}
