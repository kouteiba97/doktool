import { ApiProperty } from '@nestjs/swagger';
import { IsEnum, IsString, MaxLength, MinLength } from 'class-validator';
import { DemoContext } from '../../generated/prisma/enums.js';
import type { DemoSessionGrant } from './demo.service.js';

export class StartDemoDto {
  @ApiProperty({ enum: DemoContext, enumName: 'DemoContext', description: 'Médecin or Résident.' })
  @IsEnum(DemoContext)
  demoContext!: DemoContext;

  @ApiProperty({ description: 'Installation id generated by the app (stored hashed).' })
  @IsString()
  @MinLength(8)
  @MaxLength(128)
  deviceId!: string;
}

export class RenewDemoTokenDto {
  @ApiProperty()
  @IsString()
  @MinLength(20)
  @MaxLength(200)
  renewalToken!: string;

  @ApiProperty()
  @IsString()
  @MinLength(8)
  @MaxLength(128)
  deviceId!: string;
}

export class DemoTokenDto {
  @ApiProperty({ description: 'Demo access token (audience doktool-demo), valid 1 hour.' })
  accessToken!: string;

  @ApiProperty({ format: 'date-time' })
  accessTokenExpiresAt!: string;
}

export class DemoSessionDto extends DemoTokenDto {
  @ApiProperty({ format: 'uuid' })
  demoSessionId!: string;

  @ApiProperty({ enum: DemoContext, enumName: 'DemoContext' })
  demoContext!: DemoContext;

  @ApiProperty({
    description: 'Keep in secure storage; trades for new access tokens from this device.',
  })
  renewalToken!: string;

  static from(grant: DemoSessionGrant): DemoSessionDto {
    return {
      demoSessionId: grant.demoSessionId,
      demoContext: grant.demoContext,
      accessToken: grant.accessToken,
      accessTokenExpiresAt: grant.accessTokenExpiresAt.toISOString(),
      renewalToken: grant.renewalToken,
    };
  }
}
